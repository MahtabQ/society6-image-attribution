def clean_attribute_column(values, allowed_set):
    try:
        if isinstance(values, str):
            values = ast.literal_eval(values)
        if not isinstance(values, list):
            values = [values]

        # Create a lookup with lowercase keys for case-insensitive matching
        allowed_lookup = {val.lower(): val for val in allowed_set}

        filtered = []
        for item in values:
            if isinstance(item, dict) and 'value' in item:
                val = item['value']
                val_clean = str(val).strip().lower()
                if val_clean in allowed_lookup:
                    item['value'] = allowed_lookup[val_clean]
                    filtered.append(item)
            elif isinstance(item, str):
                val_clean = item.strip().lower()
                if val_clean in allowed_lookup:
                    filtered.append({'value': allowed_lookup[val_clean], 'confidence': 100})

        if not filtered:
            return [{'value': 'None', 'confidence': 100}]
        return filtered
    except Exception:
        return [{'value': 'None', 'confidence': 100}]


def clean_keywords_column(values, replacement_map, removal_set):
    try:
        if isinstance(values, str):
            values = ast.literal_eval(values)
        if not isinstance(values, list):
            values = [values]

        filtered = []
        for item in values:
            keyword = item['value'] if isinstance(item, dict) and 'value' in item else str(item)
            keyword_clean = keyword.strip()
            keyword_lower = keyword_clean.lower()

            try:
                keyword_clean.encode('ascii')
            except UnicodeEncodeError:
                continue

            if keyword_lower.startswith("stylized ") and keyword_lower != "stylized":
                keyword_clean = keyword_clean[len("stylized "):].lstrip()
                keyword_lower = keyword_clean.lower()

            if keyword_lower in removal_set:
                continue

            if keyword_lower in replacement_map:
                keyword_clean = replacement_map[keyword_lower]

            confidence = item.get('confidence', 100) if isinstance(item, dict) else 100
            filtered.append({'value': keyword_clean, 'confidence': confidence})

        if not filtered:
            return [{'value': 'None', 'confidence': 100}]
        return filtered
    except Exception:
        return [{'value': 'None', 'confidence': 100}]


